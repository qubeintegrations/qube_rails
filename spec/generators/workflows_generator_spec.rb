# frozen_string_literal: true

require "fileutils"
require "tmpdir"
require "generators/qube_rails/workflows_generator"

RSpec.describe QubeRails::Generators::WorkflowsGenerator do
  let(:document) { JSON.parse(File.read(File.expand_path("../fixtures/workflow_types.json", __dir__))) }
  let(:calls) { [] }

  around do |example|
    Dir.mktmpdir do |dir|
      @root = dir
      example.run
    end
    Object.send(:remove_const, :QubeWorkflows) if defined?(QubeWorkflows)
  end

  # QubeRails.client's workflow_types answers from answers (a document, :not_modified, or an
  # exception to raise), for the generator and for its check alike; the rendering is the gem's own.
  def answer(*answers)
    seen = calls
    allow(QubeRails.client).to receive(:workflow_types) do |include_drafts: false, etag: nil|
      seen << { include_drafts: include_drafts, etag: etag }
      next_answer = answers.shift
      raise next_answer if next_answer.is_a?(Exception) || (next_answer.is_a?(Class) && next_answer <= Exception)

      next_answer
    end
  end

  def generate(*args)
    $stdout = StringIO.new
    described_class.new([], args, destination_root: @root).invoke_all
    $stdout.string
  ensure
    $stdout = STDOUT
  end

  # The status a run exits with: 0 when it doesn't exit.
  def exit_status(*args)
    generate(*args)
    0
  rescue SystemExit => e
    e.status
  end

  def read(path)
    File.read(File.join(@root, path))
  end

  it "writes app/qube/qube_workflows.rb and its RBS, starting runs on QubeRails.client" do
    answer(document)
    generate

    ruby = read("app/qube/qube_workflows.rb")
    expect(ruby).to start_with("# Generated by `bin/rails g qube_rails:workflows` from #{QubeRailsHelpers::BASE_URL}/api/v2/workflows/types")
    expect(ruby).to include("module QubeWorkflows", "client: ::QubeRails.client", "# drafts: false")
    expect(ruby).not_to include("attr_writer :client", "module Resolve")
    expect(read("sig/qube_workflows.rbs")).to include("type invoice_input = {")
    expect(calls).to eq([{ include_drafts: false, etag: nil }])
  end

  it "types drafts with --drafts" do
    answer(document)
    generate("--drafts")

    expect(read("app/qube/qube_workflows.rb")).to include("# drafts: true", "module Resolve")
    expect(calls.first[:include_drafts]).to be(true)
  end

  it "writes a file whose starts go to QuBe Sync, and whose inputs an operation can return" do
    answer(document)
    generate
    load File.join(@root, "app/qube/qube_workflows.rb")
    owner = Account.create!(name: "Acme")
    connection = make_connection(owner)
    stub = stub_request(:post, api_url("/connections/#{QubeRailsHelpers::QUBE_ID}/workflow-runs"))
           .with(body: { workflow: "add_transaction", reference: "invoice-1", webhook_url: "https://app.example/runs",
                         input: { operation: "invoice.create", params: { ref_number: "1001" } } })
           .to_return(json_data("id" => "run-q"))

    run = QubeWorkflows.add_transaction.invoice(connection, { ref_number: "1001" }, reference: "invoice-1",
                                                                                 webhook_url: "https://app.example/runs")
    expect(run).to eq("id" => "run-q")
    expect(stub).to have_been_requested
    expect(QubeWorkflows::Upsert.customer_input(add: { name: "Acme" }, update: {}, class: "Wholesale"))
      .to eq(kind: "customer", add: { name: "Acme" }, class: "Wholesale", update: {})
  end

  it "warns when QuBe Sync's operations aren't the gem's" do
    answer(document)
    expect(generate).to include("warning", "operations")
  end

  it "fails when QuBe Sync refuses the key, writing nothing" do
    answer(QubeRails::Backend::APIError.new(status: 401, body: ""))
    expect(exit_status).to eq(1)
    expect(File.exist?(File.join(@root, "app/qube/qube_workflows.rb"))).to be(false)
  end

  describe "--check" do
    before do
      answer(document)
      generate("--drafts")
    end

    it "passes on a 304, asking with the file's digest and drafts flag" do
      answer(:not_modified)
      expect(exit_status("--check")).to eq(0)
      expect(calls.last).to eq(include_drafts: true, etag: document["digest"])
    end

    it "fails when the digest differs, naming what changed" do
      changed = document.merge("digest" => "sha256:#{'d' * 64}")
      changed["workflows"] = document["workflows"].reject { |key, _| key == "upsert" }
      answer(changed)
      output = nil
      status = begin
        $stdout = StringIO.new
        described_class.new([], ["--check"], destination_root: @root).invoke_all
        0
      rescue SystemExit => e
        e.status
      ensure
        output = $stdout.string
        $stdout = STDOUT
      end
      expect(status).to eq(1)
      expect(output).to include("upsert (removed)", "bin/rails g qube_rails:workflows --drafts")
    end

    it "warns and passes when QuBe Sync can't be reached or answers 5xx" do
      answer(Errno::ECONNREFUSED, QubeRails::Backend::APIError.new(status: 503, body: ""))
      expect(exit_status("--check")).to eq(0)
      expect(exit_status("--check")).to eq(0)
    end

    it "fails on a 401" do
      answer(QubeRails::Backend::APIError.new(status: 401, body: ""))
      expect(exit_status("--check")).to eq(1)
    end

    it "fails when there's no file" do
      FileUtils.rm(File.join(@root, "app/qube/qube_workflows.rb"))
      expect(exit_status("--check")).to eq(1)
    end
  end

  it "fetches through the client: GET /api/v2/workflows/types" do
    stub = stub_request(:get, api_url("/workflows/types")).with(query: { include: "drafts" })
                                                       .to_return(json_data(document))
    expect(QubeRails::Backend.workflow_types(QubeRails.client, include_drafts: true)).to eq(document)
    expect(stub).to have_been_requested
  end
end
